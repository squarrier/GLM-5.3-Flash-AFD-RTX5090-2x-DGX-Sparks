//! grammar_abi build (Claude Opus 5.5 via Hermes): libtfgrammar exactly as TensorFold release v1.0.6 (c080a18e)
//! zig/build/grammar.zig library() compiles it, the ABI test runner, and refusal fixtures.
//! One deliberate recipe difference, recorded in RESULTS.md: the release's `git describe --tags --exact-match`
//! tag-name check (grammar.zig:31-33) cannot run in the git-less pinned image, so the checkout is locked instead
//! by scripts/verify_sources.py (commit 97787376, tag object 520e25b1, dlpack bbd2f4d3, picojson tree 0d9c226c,
//! per-file sha256 manifest) before every build. Module options, flags, include paths and the compile list are the
//! release's: sources.zig is generated by the release sources() rule (every cpp/**.cc except cpp/tvm_ffi).
const std = @import("std");
const listed = @import("sources.zig");

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const dir = b.option([]const u8, "xgrammar", "the verified xgrammar 97787376 checkout") orelse "/xgrammar";
    const shim = b.option([]const u8, "shim", "the shim source relative to this build root") orelse "zig/src/grammar/tf_grammar.cc";

    const grammar = b.step("grammar", "libtfgrammar from the verified xgrammar checkout");
    grammar.dependOn(&b.addInstallArtifact(library(b, target, dir, shim), .{ .dest_dir = .{ .override = .{ .custom = "lib" } } }).step);

    // a library exporting every release symbol but tfg_drafts, each body abort(): proves no foreign call happens before symbol checks
    const stub_mod = b.createModule(.{ .target = target, .optimize = .ReleaseSafe, .link_libc = true });
    stub_mod.addCSourceFile(.{ .file = b.path("fixtures/abort_stub.c"), .flags = &.{"-std=c11"} });
    const stub = b.addLibrary(.{ .name = "tfgabortstub", .linkage = .dynamic, .root_module = stub_mod });
    const fixtures = b.step("fixtures", "refusal fixture libraries");
    fixtures.dependOn(&b.addInstallArtifact(stub, .{ .dest_dir = .{ .override = .{ .custom = "fixtures" } } }).step);

    const tests = b.addExecutable(.{ .name = "grammar_abi_tests", .root_module = b.createModule(.{
        .root_source_file = b.path("src/abi_tests.zig"),
        .target = target,
        .optimize = .ReleaseSafe,
        .link_libc = true,
    }) });
    const t = b.step("tests", "the ABI test runner (loads the library at run time through tfg_trusted.zig)");
    t.dependOn(&b.addInstallArtifact(tests, .{}).step);
}

/// Release zig/build/grammar.zig:34-44 with the shim path as a parameter (the release hard-codes the release shim).
fn library(b: *std.Build, target: std.Build.ResolvedTarget, dir: []const u8, shim: []const u8) *std.Build.Step.Compile {
    const root: std.Build.LazyPath = .{ .cwd_relative = dir };
    const mod = b.createModule(.{ .target = target, .optimize = .ReleaseFast, .link_libcpp = true, .strip = true });
    // xgrammar's checks keep __FILE__: the map keeps the checkout's absolute path out of the shipped library
    const map = b.fmt("-ffile-prefix-map={s}=xgrammar", .{dir});
    const flags = [_][]const u8{ "-std=c++17", "-DXGRAMMAR_ENABLE_CPPTRACE=0", "-fexceptions", "-Wno-everything", map };
    mod.addIncludePath(root.path(b, "include"));
    mod.addIncludePath(root.path(b, "3rdparty/picojson"));
    mod.addIncludePath(root.path(b, "3rdparty/dlpack/include"));
    mod.addCSourceFiles(.{ .root = root, .files = &listed.files, .flags = &flags });
    mod.addCSourceFile(.{ .file = b.path(shim), .flags = &flags });
    return b.addLibrary(.{ .name = "tfgrammar", .linkage = .dynamic, .root_module = mod });
}
